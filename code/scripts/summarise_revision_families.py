r"""Summarise saved full-test family recall; never starts training.

Run from the code directory: .venv\Scripts\python.exe scripts/summarise_revision_families.py
"""
import json
import math
import statistics
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from audit_revision_numerics import issues_for_run

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "revision_full_corpus"
PAPER = ROOT.parent / "paper"
SEEDS = (42, 43, 44)
FAMILIES = ("Benign", "DDoS", "DoS", "Mirai", "MITM_Spoof", "Recon", "Injection", "Malware_BF")
LABELS = {"MITM_Spoof": "MITM / spoofing", "Malware_BF": "Malware / BF"}


def main():
    runs = {}
    numerical_issues = {}
    supports = None
    for path in sorted((OUT / "runs").glob("*.json")):
        run = json.loads(path.read_text(encoding="utf-8"))
        seed = run["revision_evidence"]["seed"]
        if seed not in SEEDS:
            continue
        name = run["config"]["name"]
        numerical_issues[name, seed] = issues_for_run(run)
        assert not run["config"]["dp"], path
        assert run["dataset"]["eval_rows"] == 4673255, path
        families = run["final"]["per_category"]
        assert set(families) == set(FAMILIES), path
        counts = {k: families[k]["support"] for k in FAMILIES}
        assert sum(counts.values()) == 4673255, path
        if supports is None:
            supports = counts
        assert counts == supports, path
        assert seed not in runs.setdefault(name, {}), path
        runs[name][seed] = families
    assert len(runs) == 9, "Expected nine conditions"
    rows = []
    for name, by_seed in runs.items():
        assert set(by_seed) == set(SEEDS), name
        for family in FAMILIES:
            values = [by_seed[s][family]["recall"] for s in SEEDS]
            assert all(math.isfinite(v) and 0 <= v <= 1 for v in values)
            rows.append(dict(condition=name, family=family, support=supports[family],
                             numerical_issues_by_seed={str(s): numerical_issues[name, s] for s in SEEDS if numerical_issues[name, s]},
                             seeds=list(SEEDS), recall_by_seed=values,
                             recall_mean=statistics.mean(values),
                             recall_std=statistics.stdev(values)))
    payload = dict(metric_source="final.per_category: complete held-out evaluation",
                   eval_rows=4673255, dp=False, fixed_partition=True,
                   uncertainty="sample standard deviation across training seeds", rows=rows)
    (OUT / "full_test_family_recall.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    lines = ["# Full-test family recall", "",
             "WARNING: Metrics from runs with non-finite timeline values are unvalidated; see NUMERICAL_INTEGRITY_AUDIT.md and numerical_issues_by_seed in the JSON.", "",
             "All nine non-private conditions; three training seeds on one fixed partition.",
             "Mean +/- sample SD, not confidence intervals. Support is identical across runs.",
             "Static adaptive and f=3 are equivalent configurations, not independent evidence.", "",
             "| Condition | Family | Test support | Recall |", "|---|---|---:|---:|"]
    for r in rows:
        lines.append(f"| {r['condition']} | {r['family']} | {r['support']} | {r['recall_mean']:.6f} +/- {r['recall_std']:.6f} |")
    (OUT / "FULL_TEST_FAMILY_RECALL.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    lookup = {(r["condition"], r["family"]): r for r in rows}
    conditions = ("ran_features_retained", "ran_features_masked")
    if any(numerical_issues[c, s] for c in conditions for s in SEEDS):
        raise RuntimeError("Clean feature figure blocked by numerical failures")
    tex = [r"% Generated by summarise_revision_families.py from saved full-test metrics.",
           r"\begin{table}[H]", r"\centering", r"\small",
           r"\caption{\rev{Full-test family recall for clean, non-private runs with synthetic radio features retained or masked. Mean $\pm$ sample SD over three training seeds on the same partition.}}",
           r"\label{tab:revision-family-recall}", r"{\color{blue}",
           r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
           r"Family & Test support & Retained & Masked \\", r"\midrule"]
    for family in FAMILIES:
        a, b = (lookup[c, family] for c in conditions)
        tex.append(f"{LABELS.get(family, family)} & \\num{{{a['support']}}} & "
                   f"${a['recall_mean']:.3f}\\pm{a['recall_std']:.3f}$ & "
                   f"${b['recall_mean']:.3f}\\pm{b['recall_std']:.3f}$ " + r"\\")
    tex += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}"]
    generated = PAPER / "generated"
    generated.mkdir(exist_ok=True)
    (generated / "revision_family_recall.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    fig, ax = plt.subplots(figsize=(9, 4.8))
    for condition, offset, color, label in zip(conditions, (-.13, .13), ("#2166ac", "#b2182b"), ("Radio features retained", "Radio features masked")):
        data = [lookup[condition, f] for f in FAMILIES]
        ax.errorbar([r["recall_mean"] for r in data], [i + offset for i in range(8)],
                    xerr=[r["recall_std"] for r in data], fmt="o", capsize=3, color=color, label=label)
    ax.set_yticks(range(8), [f"{LABELS.get(f, f)} (n={supports[f]:,})" for f in FAMILIES])
    ax.invert_yaxis()
    ax.set_xlim(-.04, 1.07)
    ax.set_xlabel("Full-test recall (mean +/- sample SD; 3 training seeds)")
    ax.set_title("Family-level dependence on synthetic radio features")
    ax.grid(axis="x", alpha=.25)
    ax.legend(loc="lower right", fontsize=9)
    fig.tight_layout()
    for folder in (OUT / "figures", PAPER / "figures" / "revision_full_corpus"):
        folder.mkdir(parents=True, exist_ok=True)
        fig.savefig(folder / "fig_full_family_recall.pdf", bbox_inches="tight")
        fig.savefig(folder / "fig_full_family_recall.png", dpi=400, bbox_inches="tight")
    plt.close(fig)
    print("Verified 27 runs, 72 family summaries; exported table, JSON, Markdown, PDF and PNG.")
    for family in ("Injection", "Malware_BF", "Recon"):
        for condition in conditions:
            print(lookup[condition, family])


if __name__ == "__main__":
    main()
